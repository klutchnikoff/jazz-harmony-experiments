"""Export the article's values as JSON and as generated LaTeX macros.

Every script named ART-<subsection title>.py produces the values of exactly one
subsection and calls :func:`export`. Values are versioned as JSON in the
experiments repository. When the sibling manuscript is present, the same call
also refreshes ``TeX/generated/article-values.tex``. LaTeX therefore compiles
the last evaluated results without running Python or the scientific pipeline.
"""

import hashlib
import json
from pathlib import Path


ARTICLE_ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = Path(__file__).resolve().parent / "article-data"
MANUSCRIPT = ARTICLE_ROOT / "TeX" / "main.tex"
TEX_VALUES = ARTICLE_ROOT / "TeX" / "generated" / "article-values.tex"

SMALL_NUMBERS = {
    0: "zero", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five",
    6: "six", 7: "seven", 8: "eight", 9: "nine", 10: "ten",
    11: "eleven", 12: "twelve", 13: "thirteen", 14: "fourteen",
    15: "fifteen", 16: "sixteen", 17: "seventeen", 18: "eighteen",
    19: "nineteen", 20: "twenty", 21: "twenty-one", 22: "twenty-two",
    23: "twenty-three", 24: "twenty-four", 25: "twenty-five",
    26: "twenty-six", 27: "twenty-seven", 28: "twenty-eight",
    29: "twenty-nine", 30: "thirty", 31: "thirty-one", 32: "thirty-two",
}


def _atomic_write(path, text):
    """Replace ``path`` only after its complete new contents are on disk."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    temporary.write_text(text)
    temporary.replace(path)


def _english_list(values):
    if not values:
        return ""
    if len(values) == 1:
        return values[0]
    if len(values) == 2:
        return f"{values[0]} and {values[1]}"
    return f"{', '.join(values[:-1])}, and {values[-1]}"


def _tex_escape(value):
    replacements = {
        "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
        "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
        "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(character, character)
                   for character in str(value))


def _tex_value(value):
    """Render one JSON value for insertion in prose or mathematics."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return f"{value:,}".replace(",", "{,}")
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, str):
        return _tex_escape(value)
    if isinstance(value, list):
        rendered = [_tex_value(item) for item in value]
        if all(isinstance(item, str) for item in value):
            return _english_list(rendered)
        return ",".join(rendered)
    raise TypeError(f"unsupported article value {value!r}")


def load_all():
    """Every exported subsection, as ``{name: {key: value}}``."""
    if not DATA_DIR.exists():
        return {}
    return {
        path.stem: json.loads(path.read_text())
        for path in sorted(DATA_DIR.glob("*.json"))
    }


def render_tex_values(exported=None):
    """Render every versioned JSON value as a namespaced LaTeX macro."""
    exported = load_all() if exported is None else exported
    canonical = json.dumps(exported, sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256(canonical.encode()).hexdigest()
    lines = [
        "% GENERATED BY jazz-harmony-experiments/article_data.py",
        "% DO NOT EDIT BY HAND",
        f"% article-data-sha256: {digest}",
        r"\newcommand{\ArticleValue}[2]{\ifcsname article@#1@#2\endcsname\csname article@#1@#2\endcsname\else\PackageError{article-values}{Unknown value `#1/#2'}{}\fi}",
        r"\newcommand{\ArticleValueThin}[2]{\ifcsname article-thin@#1@#2\endcsname\csname article-thin@#1@#2\endcsname\else\PackageError{article-values}{No thin-grouped form for `#1/#2'}{}\fi}",
        r"\newcommand{\ArticleValueWord}[2]{\ifcsname article-word@#1@#2\endcsname\csname article-word@#1@#2\endcsname\else\PackageError{article-values}{No word form for `#1/#2'}{}\fi}",
        r"\newcommand{\ArticleValueWordCap}[2]{\ifcsname article-word-cap@#1@#2\endcsname\csname article-word-cap@#1@#2\endcsname\else\PackageError{article-values}{No capitalized word form for `#1/#2'}{}\fi}",
        "",
    ]
    for section, values in sorted(exported.items()):
        lines.append(f"% {section}")
        for key, value in sorted(values.items()):
            lines.append(
                rf"\expandafter\def\csname article@{section}@{key}\endcsname"
                rf"{{{_tex_value(value)}}}"
            )
            if isinstance(value, int) and not isinstance(value, bool) \
                    and value in SMALL_NUMBERS:
                word = SMALL_NUMBERS[value]
                lines.append(
                    rf"\expandafter\def\csname article-word@{section}@{key}\endcsname"
                    rf"{{{word}}}"
                )
                lines.append(
                    rf"\expandafter\def\csname article-word-cap@{section}@{key}\endcsname"
                    rf"{{{word.capitalize()}}}"
                )
            if isinstance(value, int) and not isinstance(value, bool):
                thin = f"{value:,}".replace(",", r"\,")
                lines.append(
                    rf"\expandafter\def\csname article-thin@{section}@{key}\endcsname"
                    rf"{{{thin}}}"
                )
        lines.append("")
    return "\n".join(lines)


def write_tex_values():
    """Refresh the sibling manuscript snapshot when that repository exists."""
    if not MANUSCRIPT.exists():
        return None
    _atomic_write(TEX_VALUES, render_tex_values())
    return TEX_VALUES


def export(name, values):
    """Write one subsection's JSON and refresh the manuscript macro snapshot."""
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    path = DATA_DIR / f"{name}.json"
    _atomic_write(path, json.dumps(values, indent=2, sort_keys=True) + "\n")
    print(f"exported {len(values)} values to {path.parent.name}/{path.name}")
    tex_path = write_tex_values()
    if tex_path is not None:
        print(f"refreshed LaTeX macros in {tex_path.relative_to(ARTICLE_ROOT)}")
    return path
